#!/usr/bin/env python3
"""Generates runtime/src/gx/shader_setups.inc: the shader setups (program keys) built ahead of use at startup, so the
first time an effect shows up doesn't wait for its shader to compile (see gx_gpu.cpp, "shader setups"). The game
records every setup it meets in <game folder>/shadercache/setups.txt; this merges such files (from play-throughs)
with the setups already in the list. Run from the repository root:
    python3 tools/make_shader_setups.py path/to/setups.txt [more setups.txt ...]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "runtime", "src", "gx", "shader_setups.inc")
HEADER = "ssne-shader-setups 1"  # kSetupsHeader in gx_gpu.cpp


def read_list(lines):
    lines = [l.strip() for l in lines]
    if not lines or lines[0] != HEADER:
        return None
    return [l for l in lines[1:] if l and len(l) % 2 == 0 and all(c in "0123456789abcdef" for c in l)]


def main():
    keys = set()
    if os.path.exists(OUT):  # the current list: the string literal lines after the header
        with open(OUT) as f:
            lits = [l.strip()[1:-3] for l in f if l.strip().startswith('"') and l.strip().endswith('\\n"')]
        keys.update(read_list(lits) or [])
    before = len(keys)
    for path in sys.argv[1:]:
        with open(path) as f:
            got = read_list(f.read().splitlines())
        if got is None:
            sys.exit(f"{path}: not a setups list ({HEADER})")
        keys.update(got)
    with open(OUT, "w") as f:
        f.write("// Shader setups met while playing through the game, built ahead of use (see gx_gpu.cpp, \"shader setups\").\n")
        f.write("// Generated by tools/make_shader_setups.py from setups.txt files: header line, then one program key (hex) per line.\n")
        f.write("constexpr const char* kShippedSetups =\n")
        f.write(f'    "{HEADER}\\n"\n')
        for k in sorted(keys):
            f.write(f'    "{k}\\n"\n')
        f.write("    ;\n")
    print(f"{OUT}: {len(keys)} setups ({len(keys) - before} new)")


if __name__ == "__main__":
    main()
