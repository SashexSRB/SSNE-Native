// ssne-symbols: names functions in main.dol and writes a symbol file for ssne-recomp --map.
//   ssne-symbols <main.dol> <out.sym> [--dsy Dolphin/Sys/totaldb.dsy]... [--manual existing.sym]
//                [--ref other_game/symbols.txt]... [--sdk-start 801B0000]
// Manual entries always win over automatic ones.
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>

#include "analysis.h"
#include "gc/dol.h"
#include "symbols.h"

int main(int argc, char** argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: ssne-symbols <main.dol> <out.sym> [--dsy file]... [--manual file] [--sdk-start hex]\n");
        return 2;
    }
    std::string dol_path = argv[1], out_path = argv[2], manual;
    recomp::SymbolOptions opt;
    for (int k = 3; k < argc; k++) {
        std::string a = argv[k];
        if (a == "--dsy" && k + 1 < argc) opt.dsy_files.push_back(argv[++k]);
        else if (a == "--manual" && k + 1 < argc) manual = argv[++k];
        else if (a == "--ref" && k + 1 < argc) opt.ref_files.push_back(argv[++k]);
        else if (a == "--sdk-start" && k + 1 < argc) opt.sdk_region_start = uint32_t(strtoul(argv[++k], nullptr, 16));
    }

    std::ifstream in(dol_path, std::ios::binary);
    std::vector<uint8_t> data((std::istreambuf_iterator<char>(in)), {});
    gc::Dol dol;
    std::string err;
    if (!gc::Dol::parse(data, dol, err)) { fprintf(stderr, "error: %s\n", err.c_str()); return 1; }

    // Function starts use the same analysis as the recompiler (plus manual names).
    recomp::AnalysisOptions aopt;
    aopt.symbol_map = manual;
    std::string alog;
    auto an = recomp::analyze(dol, aopt, alog);

    std::string log;
    auto syms = recomp::identify_symbols(dol, an, opt, log);
    fputs(log.c_str(), stdout);

    // Manual file: keep its lines verbatim (comments included) and let them override.
    std::map<uint32_t, recomp::NamedSymbol> merged = syms;
    std::vector<std::string> header;
    if (!manual.empty()) {
        std::ifstream m(manual);
        std::string line;
        while (std::getline(m, line)) {
            if (line.empty() || line[0] == '#') { if (line.rfind("# ---", 0) == 0) break; header.push_back(line); continue; }
            std::istringstream ss(line);
            std::string addr, name, src;
            ss >> addr >> name >> src;
            if (addr.size() != 8 || name.empty()) continue;
            if (!src.empty() && src != "manual") continue; // previously generated entries are recomputed
            merged[uint32_t(strtoul(addr.c_str(), nullptr, 16))] = {name, "manual", 0};
        }
    }

    std::ofstream o(out_path);
    for (auto& h : header) o << h << "\n";
    size_t counts[4] = {};
    o << "# --- generated by ssne-symbols: ADDRESS NAME SOURCE (manual/dsy/ref/string) ---\n";
    for (auto& [a, s] : merged) {
        char buf[16];
        snprintf(buf, sizeof(buf), "%08X", a);
        o << buf << " " << s.name << " " << s.source << "\n";
        counts[s.source == "manual" ? 0 : s.source == "dsy" ? 1 : s.source == "ref" ? 2 : 3]++;
    }
    printf("wrote %s: %zu manual, %zu signature, %zu reference-layout, %zu string (of %zu functions)\n",
           out_path.c_str(), counts[0], counts[1], counts[2], counts[3], an.functions.size());
    return 0;
}
